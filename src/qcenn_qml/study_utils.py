"""Reproducible experiment scheduling, independent seeds and clustered summaries.

This module controls experiments, never quantum model inference. Child processes
own disjoint CPU budgets and logs. Interrupted studies retain atomic checkpoints.
"""
import argparse
import hashlib
import importlib
import json
import os
from pathlib import Path
import signal
import subprocess
import sys
import time
import traceback

import numpy as np

from .recurrent_mnist import write_json


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(',', ':'),
        allow_nan=False).encode()).hexdigest()


def independent_seed(*parts):
    return int(np.random.SeedSequence([int(p) for p in parts]).generate_state(1)[0])


def circuit_digest(circuit):
    """Native gate/angle/bit-order identity, excluding autogenerated names."""
    state = hashlib.sha256()
    state.update(float(circuit.global_phase).hex().encode())
    state.update(f'{circuit.num_qubits}:{circuit.num_clbits}'.encode())
    for instruction in circuit.data:
        record = [instruction.operation.name,
            [circuit.find_bit(q).index for q in instruction.qubits],
            [circuit.find_bit(c).index for c in instruction.clbits],
            [float(value).hex() for value in instruction.operation.params]]
        state.update(json.dumps(record, separators=(',', ':')).encode())
    return state.hexdigest()


def cpu_limit():
    count = len(os.sched_getaffinity(0)) if hasattr(os, 'sched_getaffinity') else (os.cpu_count() or 1)
    path = Path('/sys/fs/cgroup/cpu.max')
    if path.exists():
        quota, period = path.read_text().split()
        if quota != 'max':
            count = min(count, max(1, (int(quota) + int(period) - 1) // int(period)))
    return count


def cluster_interval(values, groups, seed=42, repeats=1000):
    """Percentile bootstrap over sentences/data seeds, never over quantum shots."""
    values = np.asarray(values, float)
    groups = np.asarray(groups)
    if len(values) != len(groups) or not len(values):
        raise ValueError('Nonempty matched values and cluster IDs required')
    unique = np.unique(groups)
    if len(unique) < 2:
        return None
    sums = np.array([values[groups == key].sum() for key in unique])
    sizes = np.array([(groups == key).sum() for key in unique])
    draws = np.random.default_rng(seed).integers(0, len(unique), (repeats, len(unique)))
    means = sums[draws].sum(axis=1) / sizes[draws].sum(axis=1)
    return np.quantile(means, [.025, .975]).tolist()


def initialize(directory, configuration, source, resume=False):
    directory = Path(directory)
    manifest = {'configuration': configuration, 'source_sha256': source['source_sha256'],
        'runtime_packages': source.get('packages', {})}
    signature = digest(manifest)
    path = directory / 'study-manifest.json'
    if path.exists():
        previous = json.loads(path.read_text())
        if not resume or previous['signature'] != signature:
            raise FileExistsError('Use a fresh output directory, or --resume with identical settings and source')
        return previous
    if directory.exists() and any(directory.iterdir()):
        raise FileExistsError('Output contains unrelated files')
    directory.mkdir(parents=True, exist_ok=True)
    result = {**manifest, 'signature': signature, 'source': source}
    write_json(path, result)
    (directory / 'requirements-versions.txt').write_text(''.join(
        f'{name}=={version}\n' for name, version in sorted(source.get('packages', {}).items())))
    return result


def run_tasks(worker, tasks, *, jobs, cpu_budget, directory):
    """Run module:function workers in isolated processes, with resumable outputs.

    A task is {id, ...payload}. A worker writes result.json before returning.
    Result signatures prevent an old checkpoint from satisfying a changed task.
    """
    if cpu_budget < 1 or jobs < 1 or jobs > cpu_budget or cpu_budget > cpu_limit():
        raise ValueError('Require 1 <= jobs <= CPU budget <= available CPUs')
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    pending = []
    states = {}
    outputs = {}
    for task in tasks:
        name = task['id']
        if name in states or Path(name).name != name:
            raise ValueError('Task IDs must be unique plain filenames')
        target = directory / name
        target.mkdir(exist_ok=True)
        spec = {**task, 'worker': worker, 'output_dir': str(target.resolve())}
        signature = digest(spec)
        completed = target / 'completion.json'
        if completed.exists():
            previous = json.loads(completed.read_text())
            if previous['signature'] != signature:
                raise ValueError('Checkpoint/task signature mismatch: ' + name)
            if previous.get('result_sha256') != hashlib.sha256((target / 'result.json').read_bytes()).hexdigest():
                raise ValueError('Completed result changed: ' + name)
            outputs[name] = json.loads((target / 'result.json').read_text())
            states[name] = 'DONE'
        else:
            if (target / 'task.json').exists() and json.loads((target / 'task.json').read_text())['signature'] != signature:
                raise ValueError('Partial checkpoint/task signature mismatch: ' + name)
            write_json(target / 'task.json', {**spec, 'signature': signature})
            states[name] = 'PENDING'
            pending.append((name, target))
    active = {}
    failed = []
    last_update = 0.
    last_heartbeat = 0.
    threads = max(1, cpu_budget // jobs)
    environment = {**os.environ, 'QCENN_THREADS': str(threads), 'OMP_NUM_THREADS': str(threads),
        'OPENBLAS_NUM_THREADS': '1', 'MKL_NUM_THREADS': '1', 'NUMEXPR_NUM_THREADS': '1',
        'QISKIT_PARALLEL': 'FALSE', 'QISKIT_NUM_PROCS': '1'}
    def stop(signum, frame):
        raise KeyboardInterrupt('Experiment scheduler interrupted')
    previous_handlers = {s: signal.signal(s, stop) for s in (signal.SIGTERM, signal.SIGINT)}
    try:
        while pending or active:
            while pending and len(active) < jobs:
                name, target = pending.pop(0)
                stream = (target / 'worker.log').open('a', buffering=1)
                process = subprocess.Popen([sys.executable, '-u', '-m', 'qcenn_qml.study_utils',
                    '--task', str((target / 'task.json').resolve())], stdout=stream,
                    stderr=subprocess.STDOUT, env=environment, start_new_session=True)
                active[name] = process, stream, target
                states[name] = 'RUNNING'
                print(f'START {name}; threads={threads}; log={target / "worker.log"}', flush=True)
            for name, (process, stream, target) in list(active.items()):
                code = process.poll()
                if code is None:
                    continue
                stream.close()
                del active[name]
                if code == 0 and (target / 'completion.json').exists():
                    outputs[name] = json.loads((target / 'result.json').read_text())
                    states[name] = 'DONE'
                else:
                    states[name] = 'FAILED'
                    failed.append(name)
                print(f'END {name}; state={states[name]}; exit={code}', flush=True)
            if time.monotonic() - last_update >= 5:
                write_json(directory / 'status.json', {'tasks': states, 'cpu_budget': cpu_budget,
                    'workers': jobs, 'threads_per_worker': threads})
                if time.monotonic() - last_heartbeat >= 30:
                    print(f'Study progress: {sum(v == "DONE" for v in states.values())}/{len(states)} '
                        f'completed; {len(active)} active', flush=True)
                    last_heartbeat = time.monotonic()
                last_update = time.monotonic()
            if active:
                time.sleep(.2)
    finally:
        for name in active:
            states[name] = 'INTERRUPTED'
        for process, stream, _ in active.values():
            if process.poll() is None:
                os.killpg(process.pid, signal.SIGTERM)
        for process, stream, _ in active.values():
            try:
                process.wait(timeout=5)
            except subprocess.TimeoutExpired:
                os.killpg(process.pid, signal.SIGKILL)
                process.wait()
            stream.close()
        for signum, handler in previous_handlers.items():
            signal.signal(signum, handler)
        write_json(directory / 'status.json', {'tasks': states, 'failed': failed})
    if failed:
        raise RuntimeError('Experiment tasks failed; inspect worker.log: ' + ', '.join(failed))
    return [outputs[task['id']] for task in tasks]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--task', required=True)
    spec = json.loads(Path(parser.parse_args(argv).task).read_text())
    module, function = spec['worker'].split(':')
    try:
        if 'source_sha256' in spec:
            from .recurrent_mnist import provenance
            if provenance()['source_sha256'] != spec['source_sha256']:
                raise ValueError('Study source changed before worker startup; use an isolated checkout')
        result = getattr(importlib.import_module(module), function)(spec)
        write_json(Path(spec['output_dir']) / 'result.json', result)
        result_hash = hashlib.sha256((Path(spec['output_dir']) / 'result.json').read_bytes()).hexdigest()
        write_json(Path(spec['output_dir']) / 'completion.json', {'signature': spec['signature'], 'result_sha256': result_hash})
    except BaseException:
        write_json(Path(spec['output_dir']) / 'error.json', {'traceback': traceback.format_exc()})
        raise


if __name__ == '__main__':
    main()
